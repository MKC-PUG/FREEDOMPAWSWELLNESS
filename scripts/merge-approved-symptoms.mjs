#!/usr/bin/env node
/**
 * Merges approved symptom aliases from data/symptom-feedback/feedback.json
 * into lib/ai/symptom-lexicon.ts (MERGED_SYMPTOM_ENTRIES block) for git/production.
 *
 * Usage: npm run symptom:merge
 */

import { createHash } from 'crypto';
import { readFile, writeFile, mkdir } from 'fs/promises';
import path from 'path';

const root = process.cwd();
const feedbackPath = path.join(root, 'data', 'symptom-feedback', 'feedback.json');
const lexiconPath = path.join(root, 'lib', 'ai', 'symptom-lexicon.ts');

const START_MARKER = '/* MERGED_ALIASES:START';
const END_MARKER = '/* MERGED_ALIASES:END';

function escapeTsString(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function entryId(alias) {
  const hash = createHash('sha256').update(alias).digest('hex').slice(0, 10);
  return `merged_${hash}`;
}

function formatEntry(entry) {
  const aliases = entry.aliases.map((a) => `      '${escapeTsString(a)}',`).join('\n');
  return `  {
    id: '${entry.id}',
    canonical: '${escapeTsString(entry.canonical)}',
    aliases: [
${aliases}
    ],
    protocol: '${escapeTsString(entry.protocol)}',
    priority: ${entry.priority},
  }`;
}

function parseExistingMerged(content) {
  const start = content.indexOf(START_MARKER);
  const end = content.indexOf(END_MARKER);
  if (start === -1 || end === -1) {
    throw new Error('MERGED_ALIASES markers not found in symptom-lexicon.ts');
  }
  return { start, end, before: content.slice(0, start), after: content.slice(end) };
}

async function loadFeedback() {
  try {
    const raw = await readFile(feedbackPath, 'utf8');
    return JSON.parse(raw);
  } catch {
    return { approvedAliases: [] };
  }
}

function collectExistingAliases(content) {
  const existing = new Set();
  const aliasMatches = content.matchAll(/'((?:\\'|[^'])*)'/g);
  for (const match of aliasMatches) {
    existing.add(match[1].replace(/\\'/g, "'").toLowerCase());
  }
  return existing;
}

async function main() {
  const db = await loadFeedback();
  const toExport = (db.approvedAliases ?? []).filter((a) => !a.exportedToLexicon);

  let lexiconContent = await readFile(lexiconPath, 'utf8');
  const existingAliases = collectExistingAliases(lexiconContent);
  const { before, after } = parseExistingMerged(lexiconContent);

  // Keep already-exported entries from the current MERGED block by re-reading approved exported
  const allApproved = db.approvedAliases ?? [];
  const mergedEntries = [];

  for (const item of allApproved) {
    const alias = item.alias.toLowerCase().trim();
    if (!alias) continue;

    const key = `${alias}::${item.protocol}`;
    if (mergedEntries.some((e) => e.key === key)) continue;

    // Skip if already in static lexicon (not merged section)
    const staticPart = lexiconContent.split(START_MARKER)[0];
    if (staticPart.toLowerCase().includes(`'${alias.replace(/'/g, "\\'")}'`) ||
        staticPart.toLowerCase().includes(`'${alias}'`)) {
      if (!item.exportedToLexicon && toExport.find((t) => t.id === item.id)) {
        console.log(`  skip (already in base lexicon): "${alias}"`);
        item.exportedToLexicon = true;
      }
      continue;
    }

    mergedEntries.push({
      key,
      id: entryId(alias),
      canonical: item.canonical || item.alias,
      aliases: [alias],
      protocol: item.protocol,
      priority: 46,
      sourceId: item.id,
      isNew: !item.exportedToLexicon,
    });
  }

  const newCount = mergedEntries.filter((e) => e.isNew).length;

  const block = `${START_MARKER} — generated by npm run symptom:merge — do not edit manually */
export const MERGED_SYMPTOM_ENTRIES: SymptomEntry[] = [
${mergedEntries.length ? mergedEntries.map(formatEntry).join(',\n') : ''}
];
${after}`;

  await writeFile(lexiconPath, before + block, 'utf8');

  for (const item of toExport) {
    item.exportedToLexicon = true;
  }

  await mkdir(path.dirname(feedbackPath), { recursive: true });
  await writeFile(feedbackPath, JSON.stringify(db, null, 2), 'utf8');

  console.log(`\n✓ Merged ${mergedEntries.length} approved alias(es) into symptom-lexicon.ts`);
  console.log(`  New this run: ${newCount}`);
  console.log('\nNext steps:');
  console.log('  git diff lib/ai/symptom-lexicon.ts');
  console.log('  git add lib/ai/symptom-lexicon.ts && git commit -m "Expand symptom lexicon from review queue"');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

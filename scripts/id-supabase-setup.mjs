#!/usr/bin/env node
/**
 * Freedom Paws ID — Supabase setup (steps 1–3)
 *
 * Usage:
 *   npm run id:setup              # interactive
 *   npm run id:setup -- --check   # verify .env.local + DB tables only
 *   npm run id:setup -- --migrations-only  # run SQL if SUPABASE_DB_URL set
 *
 * Required for migrations (step 1):
 *   SUPABASE_DB_URL — Supabase Dashboard → Settings → Database → URI (Session pooler)
 *
 * Required for .env.local (step 2):
 *   NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY, etc.
 *
 * Step 3 (email auth): dashboard or SUPABASE_ACCESS_TOKEN + SUPABASE_PROJECT_REF
 */

import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { fileURLToPath } from 'url';
import postgres from 'postgres';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const ENV_PATH = path.join(ROOT, '.env.local');
const SQL_PATH = path.join(ROOT, 'supabase', 'RUN_ALL_MIGRATIONS_001_004.sql');

const args = new Set(process.argv.slice(2));
const CHECK_ONLY = args.has('--check');
const MIGRATIONS_ONLY = args.has('--migrations-only');

function ask(rl, q, { secret = false, defaultValue = '' } = {}) {
  const suffix = defaultValue ? ` [${defaultValue}]` : '';
  return new Promise((resolve) => {
    rl.question(`${q}${suffix}: `, (answer) => {
      const v = answer.trim() || defaultValue;
      resolve(v);
    });
  });
}

function parseProjectRef(supabaseUrl) {
  try {
    const host = new URL(supabaseUrl).hostname;
    const m = host.match(/^([a-z0-9]+)\.supabase\.co$/i);
    return m?.[1] ?? null;
  } catch {
    return null;
  }
}

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = t.indexOf('=');
    if (eq === -1) continue;
    const key = t.slice(0, eq).trim();
    let val = t.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

function writeEnvLocal(vars) {
  const lines = [
    '# Freedom Paws — generated by npm run id:setup',
    `# ${new Date().toISOString()}`,
    '',
    'NEXT_PUBLIC_SITE_MODE=preview',
    '',
    `NEXT_PUBLIC_APP_URL=${vars.NEXT_PUBLIC_APP_URL}`,
    `NEXT_PUBLIC_FRAMER_URL=${vars.NEXT_PUBLIC_FRAMER_URL || 'https://freedompawsinc.com'}`,
    '',
    `NEXT_PUBLIC_SUPABASE_URL=${vars.NEXT_PUBLIC_SUPABASE_URL}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${vars.NEXT_PUBLIC_SUPABASE_ANON_KEY}`,
    `SUPABASE_SERVICE_ROLE_KEY=${vars.SUPABASE_SERVICE_ROLE_KEY}`,
    '',
    `OPENAI_API_KEY=${vars.OPENAI_API_KEY || ''}`,
    '',
    `RESEND_API_KEY=${vars.RESEND_API_KEY || ''}`,
    `RESEND_FROM_EMAIL=${vars.RESEND_FROM_EMAIL || 'Freedom Paws ID <onboarding@resend.dev>'}`,
    '',
    `FP_OPS_EMAILS=${vars.FP_OPS_EMAILS}`,
    '',
    '# Optional — copy from existing Vercel env if you have them:',
    '# NEXT_PUBLIC_XUMM_API_KEY=',
    '# XUMM_API_SECRET=',
    '# XRPL_TREASURY_ADDRESS=',
    '# ADMIN_PASSWORD=',
    '',
    '# Database URI for re-running migrations: Settings → Database → Connection string',
    vars.SUPABASE_DB_URL ? `SUPABASE_DB_URL=${vars.SUPABASE_DB_URL}` : '# SUPABASE_DB_URL=',
    '',
  ];
  fs.writeFileSync(ENV_PATH, lines.join('\n'));
  console.log(`\n✓ Wrote ${ENV_PATH}`);
}

async function runMigrations(dbUrl) {
  if (!fs.existsSync(SQL_PATH)) {
    throw new Error(`Missing ${SQL_PATH} — run npm run id:migrations:merge first`);
  }
  const sqlText = fs.readFileSync(SQL_PATH, 'utf8');
  console.log('\nRunning migrations against Supabase (may take 30–60s)…');
  const sql = postgres(dbUrl, { max: 1, idle_timeout: 30, connect_timeout: 30 });
  try {
    await sql.unsafe(sqlText);
    console.log('✓ Migrations 001–004 applied successfully');
  } finally {
    await sql.end({ timeout: 5 });
  }
}

async function verifyTables(dbUrl) {
  const sql = postgres(dbUrl, { max: 1 });
  try {
    const tables = [
      'pets',
      'biometric_enrollments',
      'pet_embeddings',
      'found_dog_reports',
      'match_candidates',
      'audit_log',
      'user_profiles',
      'shelters',
    ];
    const rows = await sql`
      select table_name
      from information_schema.tables
      where table_schema = 'public'
        and table_name = any(${tables})
    `;
    const found = new Set(rows.map((r) => r.table_name));
    const missing = tables.filter((t) => !found.has(t));
    if (missing.length) {
      console.log('✗ Missing tables:', missing.join(', '));
      return false;
    }
    console.log('✓ All ID tables present:', tables.join(', '));
    return true;
  } finally {
    await sql.end({ timeout: 5 });
  }
}

async function enableEmailAuth(projectRef, accessToken, siteUrl) {
  const body = {
    site_url: siteUrl,
    uri_allow_list: `${siteUrl}/auth/callback,http://localhost:3000/auth/callback`,
    external_email_enabled: true,
    mailer_autoconfirm: false,
  };
  const res = await fetch(`https://api.supabase.com/v1/projects/${projectRef}/config/auth`, {
    method: 'PATCH',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`Auth config API ${res.status}: ${text.slice(0, 300)}`);
  }
  console.log('✓ Email auth + redirect URLs configured via Management API');
}

async function main() {
  const fileEnv = loadEnvFile(ENV_PATH);
  const env = { ...fileEnv, ...process.env };

  if (CHECK_ONLY || MIGRATIONS_ONLY) {
    const dbUrl = env.SUPABASE_DB_URL?.trim();
    if (!dbUrl) {
      console.error('Set SUPABASE_DB_URL in .env.local (Database → Connection string URI)');
      process.exit(1);
    }
    if (MIGRATIONS_ONLY) {
      await runMigrations(dbUrl);
    }
    const ok = await verifyTables(dbUrl);
    process.exit(ok ? 0 : 1);
  }

  console.log('\nFreedom Paws ID — Supabase setup (steps 1–3)\n');
  console.log('Get keys from: Supabase Dashboard → Project Settings → API');
  console.log('DB URI from: Settings → Database → Connection string → URI (use database password)\n');

  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

  try {
    const supabaseUrl = await ask(rl, 'NEXT_PUBLIC_SUPABASE_URL', {
      defaultValue: fileEnv.NEXT_PUBLIC_SUPABASE_URL || '',
    });
    const anonKey = await ask(rl, 'NEXT_PUBLIC_SUPABASE_ANON_KEY (anon public)');
    const serviceRole = await ask(rl, 'SUPABASE_SERVICE_ROLE_KEY (service_role — keep secret)');
    const dbUrl = await ask(rl, 'SUPABASE_DB_URL (postgresql://… — for migrations)', {
      defaultValue: fileEnv.SUPABASE_DB_URL || '',
    });
    const fpOps = await ask(rl, 'FP_OPS_EMAILS (your email for match review)', {
      defaultValue: fileEnv.FP_OPS_EMAILS || '',
    });
    const appUrl = await ask(rl, 'NEXT_PUBLIC_APP_URL', {
      defaultValue: fileEnv.NEXT_PUBLIC_APP_URL || 'https://app.freedompawsinc.com',
    });
    const openai = await ask(rl, 'OPENAI_API_KEY (optional now, press Enter to skip)', {
      defaultValue: fileEnv.OPENAI_API_KEY || '',
    });
    const resendKey = await ask(rl, 'RESEND_API_KEY (optional now)', {
      defaultValue: fileEnv.RESEND_API_KEY || '',
    });

    const accessToken = await ask(
      rl,
      'SUPABASE_ACCESS_TOKEN (optional — paste from supabase.com/dashboard/account/tokens to auto-enable email auth; Enter to skip)',
      { defaultValue: '' }
    );

    rl.close();

    if (!supabaseUrl || !anonKey || !serviceRole || !dbUrl || !fpOps) {
      console.error('\n✗ Supabase URL, anon key, service role, DB URL, and FP_OPS_EMAILS are required.');
      process.exit(1);
    }

    writeEnvLocal({
      NEXT_PUBLIC_SUPABASE_URL: supabaseUrl,
      NEXT_PUBLIC_SUPABASE_ANON_KEY: anonKey,
      SUPABASE_SERVICE_ROLE_KEY: serviceRole,
      SUPABASE_DB_URL: dbUrl,
      FP_OPS_EMAILS: fpOps,
      NEXT_PUBLIC_APP_URL: appUrl,
      OPENAI_API_KEY: openai,
      RESEND_API_KEY: resendKey,
    });

    await runMigrations(dbUrl);
    await verifyTables(dbUrl);

    const projectRef = parseProjectRef(supabaseUrl);
    if (accessToken && projectRef) {
      try {
        await enableEmailAuth(projectRef, accessToken, appUrl.replace(/\/$/, ''));
      } catch (err) {
        console.warn('\n⚠ Could not set auth via API:', err.message);
        console.warn('  Enable Email manually: Authentication → Providers → Email ON');
        console.warn(`  Site URL: ${appUrl}`);
        console.warn(`  Redirect: ${appUrl}/auth/callback and http://localhost:3000/auth/callback`);
      }
    } else {
      console.log('\n— Step 3 (manual): Supabase → Authentication → Providers → enable Email');
      console.log(`  Site URL: ${appUrl}`);
      console.log(`  Redirect URLs: ${appUrl}/auth/callback , http://localhost:3000/auth/callback`);
    }

    console.log('\n— Step 2b: Copy the same variables to Vercel → Settings → Environment Variables → Redeploy');
    console.log('— Verify local: npm run dev → http://localhost:3000/api/id/config-status');
    console.log('— Verify login: http://localhost:3000/login\n');
  } catch (err) {
    rl.close();
    console.error('\n✗ Setup failed:', err.message);
    process.exit(1);
  }
}

main();
